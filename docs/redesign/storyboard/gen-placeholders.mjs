#!/usr/bin/env node
// Tiny blur-up placeholders for every plate (UX audit: slow connections first-paint
// a flat black frame). Emits components/experience/placeholders.ts.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, '../../..');
const framesSrc = fs.readFileSync(path.join(REPO, 'components/experience/frames.ts'), 'utf8');
const media = [...new Set([...framesSrc.matchAll(/\$\{M\}\/([\w.-]+)/g)].map((m) => m[1]))];
const out = {};
for (const f of media) {
  const src = path.join(REPO, 'public/images/experience/photo', f);
  if (!fs.existsSync(src)) { console.error('missing', f); continue; }
  const tmp = `/tmp/ph-${f}.jpg`;
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', src, '-vf', 'scale=16:-2', '-q:v', '8', tmp]);
  out[`/images/experience/photo/${f}`] = `data:image/jpeg;base64,${fs.readFileSync(tmp).toString('base64')}`;
}
const ts = `// Generated by docs/redesign/storyboard/gen-placeholders.mjs — do not edit.
// 16px blur-up placeholders so slow connections never paint a flat black plate.
export const PLACEHOLDERS: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(REPO, 'components/experience/placeholders.ts'), ts);
console.log(`placeholders.ts: ${Object.keys(out).length} plates`);
